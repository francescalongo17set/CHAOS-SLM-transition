"""Data audit (handbook chapter 02). Read-only. Writes audit_report.md.

Usage: python audit.py [--data DIR] [--out FILE] [--token-lengths FILE.json]
Token lengths (item 6) are filled in by a second pass once the reference
tokenizer exists (P0 step 7): pass the JSON it writes via --token-lengths.
"""
import argparse
import hashlib
import json
import statistics
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_DATA = HERE.parents[2] / "data-generation" / "data" / "final"
EXPECTED = {"train": 2092, "validation": 298, "test": 593}
SCOPE = {"in_scope", "out_of_scope", "quick_reply"}
FEATURES = {"regulatory_consultation", "product_policy_analysis", "comparison",
            "ibip_screening", "client_drafting", "none"}
ROUTES = {"lightweight", "agentic", "clarification", "refuse", "quick_reply"}
SLOT_STATUS = {"present", "missing", "ambiguous"}
CHAPTER02_SLOTS = {
    "product_policy_analysis": {"insurer", "product", "field", "coverage"},
    "comparison": {"insurer", "product", "field", "coverage"},
    "client_drafting": {"product", "client_profile", "message_goal"},
    "ibip_screening": {"product", "client_profile"},
    "regulatory_consultation": {"topic", "date_reference"},  # date_reference on some rows
}


def load(path):
    rows = []
    with open(path, encoding="utf-8") as f:
        for i, line in enumerate(f, 1):
            line = line.strip()
            if line:
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError as e:
                    rows.append({"_bad_line": i, "_error": str(e)})
    return rows


def pct(n, d):
    return f"{n} ({100 * n / d:.1f}%)" if d else f"{n}"


def table(counter, header):
    out = [f"| {header} | n |", "|---|---|"]
    for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], str(kv[0]))):
        out.append(f"| {k} | {v} |")
    return "\n".join(out)


def check_row(r):
    """Schema violations for one row (item 8)."""
    v = []
    if "_bad_line" in r:
        return [f"unparseable JSON at line {r['_bad_line']}"]
    for k in ("query_id", "query", "context", "labels", "support"):
        if k not in r:
            return [f"missing key {k}"]
    ctx, lab, sup = r["context"], r["labels"], r["support"]
    for k in ("history", "available_docs"):
        if k not in ctx:
            v.append(f"context.{k} missing")
    if lab.get("scope_check") not in SCOPE:
        v.append(f"bad scope_check {lab.get('scope_check')!r}")
    if lab.get("feature") not in FEATURES:
        v.append(f"bad feature {lab.get('feature')!r}")
    if sup.get("expected_route") not in ROUTES:
        v.append(f"bad expected_route {sup.get('expected_route')!r}")
    if sup.get("language") != "it":
        v.append(f"language {sup.get('language')!r}")
    for h in ctx.get("history", []):
        if set(h) != {"role", "text"} or h["role"] not in ("user", "assistant"):
            v.append("bad history turn")
            break
    for s, st in (sup.get("slot_status") or {}).items():
        if st not in SLOT_STATUS:
            v.append(f"bad slot status {s}={st}")
    ins = lab.get("scope_check") == "in_scope"
    for k in ("complexity", "missing_info"):
        if ins and k not in lab:
            v.append(f"labels.{k} absent on in_scope row")
        if not ins and k in lab:
            v.append(f"labels.{k} present on non-in_scope row")
    if ins and lab.get("complexity") not in (None, "simple", "complex"):
        v.append(f"bad complexity {lab.get('complexity')!r}")
    if not ins and lab.get("feature") != "none":
        v.append(f"feature {lab.get('feature')!r} on non-in_scope row (expected none)")
    if ins and lab.get("feature") == "none":
        v.append("feature none on in_scope row")
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(DEFAULT_DATA))
    ap.add_argument("--out", default=str(HERE / "audit_report.md"))
    ap.add_argument("--token-lengths", default=None)
    a = ap.parse_args()
    data = Path(a.data)

    L = ["# Data audit report", "",
         "Generated by `audit/audit.py` (read-only). Compared against handbook chapter 02.",
         "`DIFF` lines need an owner decision before anything is built on top (rule 1).", ""]
    diffs = []
    suspected = []

    def diff(msg):
        diffs.append(msg)
        L.append(f"- **DIFF** {msg}")

    splits = {}
    for s in EXPECTED:
        rows = load(data / s / "router.jsonl")
        splits[s] = rows

    # 1 counts
    L += ["## 1. Row counts", "", "| split | rows | expected | status |", "|---|---|---|---|"]
    for s, exp in EXPECTED.items():
        n = len(splits[s])
        L.append(f"| {s} | {n} | {exp} | {'PASS' if n == exp else 'DIFF'} |")
        if n != exp:
            diffs.append(f"row count {s}: {n} != {exp}")
    L.append("")
    # duplicate ids / overlaps
    ids = {s: [r.get("query_id") for r in rows] for s, rows in splits.items()}
    for s in ids:
        d = [k for k, c in Counter(ids[s]).items() if c > 1]
        L.append(f"- Duplicate query_ids in {s}: {len(d)}" + (f" ({d[:5]})" if d else ""))
        if d:
            diffs.append(f"duplicate query_ids in {s}")
    for x, y in (("train", "validation"), ("train", "test"), ("validation", "test")):
        o = set(ids[x]) & set(ids[y])
        L.append(f"- query_id overlap {x}/{y}: {len(o)}")
        if o:
            diffs.append(f"query_id overlap {x}/{y}")
    qs = {s: {r.get("query") for r in rows} for s, rows in splits.items()}
    for x, y in (("train", "validation"), ("train", "test"), ("validation", "test")):
        o = qs[x] & qs[y]
        L.append(f"- identical query text overlap {x}/{y}: {len(o)} (information only)")
    L.append("")

    # 2 counts per field
    L += ["## 2. Label and support counts", ""]
    for s, rows in splits.items():
        ok = [r for r in rows if "_bad_line" not in r]
        L += [f"### {s}", ""]
        for title, fn in [
            ("scope_check", lambda r: r["labels"].get("scope_check")),
            ("feature", lambda r: r["labels"].get("feature")),
            ("complexity", lambda r: r["labels"].get("complexity", "(absent)")),
            ("expected_route", lambda r: r["support"].get("expected_route")),
            ("safety_leak", lambda r: r["support"].get("safety_leak")),
            ("leak_type", lambda r: r["support"].get("leak_type")),
            ("leak_difficulty", lambda r: r["support"].get("leak_difficulty")),
            ("context_scenario", lambda r: r["support"].get("context_scenario")),
            ("needs_clarification (gold, in_scope only)",
             lambda r: bool(r["labels"].get("missing_info")) if r["labels"].get("scope_check") == "in_scope" else "(n/a)"),
        ]:
            L += [table(Counter(fn(r) for r in ok), title), ""]

    # 3 slots per feature
    L += ["## 3. `support.required_slots` per feature", "",
          "| feature | slot lists seen (count) | matches chapter 02 |", "|---|---|---|"]
    seen = defaultdict(Counter)
    for rows in splits.values():
        for r in rows:
            if "_bad_line" in r:
                continue
            seen[r["labels"]["feature"]][tuple(r["support"].get("required_slots", []))] += 1
    for f in sorted(seen):
        lists = "; ".join(f"{list(k)} x{v}" for k, v in seen[f].most_common())
        if f in CHAPTER02_SLOTS:
            allowed = CHAPTER02_SLOTS[f]
            bad = [k for k in seen[f] if not set(k) <= allowed or not set(k) >= (allowed - {"date_reference"} if f == "regulatory_consultation" else allowed)]
            # C-28 (owner-accepted): insurer omitted, only on no_policy/ambiguous_product rows
            # whose gold route is clarification. Anything beyond that is still a DIFF.
            accepted = [k for k in bad if k == ("product", "field", "coverage")]
            ok28 = all(r["support"]["expected_route"] == "clarification"
                       and r["support"]["context_scenario"] in ("no_policy", "ambiguous_product")
                       for rows in splits.values() for r in rows
                       if "_bad_line" not in r and r["labels"]["feature"] == f
                       and tuple(r["support"].get("required_slots", [])) == ("product", "field", "coverage"))
            real = [k for k in bad if k not in accepted or not ok28]
            status = "PASS" if not bad else ("ACCEPTED (C-28)" if not real else "DIFF")
            if real:
                diffs.append(f"slot lists for {f} differ from chapter 02: {real}")
        else:
            status = "n/a (non-in_scope)"
        L.append(f"| {f} | {lists} | {status} |")
    L.append("")

    # 4 and 5 consistency
    L += ["## 4. missing_info versus route", "", "| split | missing_info non-empty | ... and route != clarification | route clarification | ... and missing_info empty | status |",
          "|---|---|---|---|---|---|"]
    for s, rows in splits.items():
        ok = [r for r in rows if "_bad_line" not in r]
        mi = [r for r in ok if r["labels"].get("missing_info")]
        a1 = [r for r in mi if r["support"]["expected_route"] != "clarification"]
        cl = [r for r in ok if r["support"]["expected_route"] == "clarification"]
        a2 = [r for r in cl if not r["labels"].get("missing_info")]
        st = "PASS" if not a1 and not a2 else "DIFF"
        L.append(f"| {s} | {len(mi)} | {len(a1)} | {len(cl)} | {len(a2)} | {st} |")
        for r in (a1 + a2)[:10]:
            diffs.append(f"{s} {r['query_id']}: missing_info={r['labels'].get('missing_info')} route={r['support']['expected_route']}")
    L.append("")
    L += ["Also checked: every slot in `missing_info` has status `missing` or `ambiguous`, and `missing_info` equals the set of non-present required slots.", ""]
    bad_mi = []
    for s, rows in splits.items():
        for r in rows:
            if "_bad_line" in r or r["labels"].get("scope_check") != "in_scope":
                continue
            ss = r["support"].get("slot_status", {})
            nonpresent = sorted(k for k, v in ss.items() if v != "present")
            if sorted(r["labels"].get("missing_info", [])) != nonpresent:
                bad_mi.append((s, r["query_id"], r["labels"].get("missing_info"), nonpresent))
    L.append(f"- Rows where `missing_info` != non-present `slot_status` slots: {len(bad_mi)}")
    for x in bad_mi[:10]:
        L.append(f"  - {x}")
    if bad_mi:
        diffs.append(f"missing_info vs slot_status mismatch on {len(bad_mi)} rows")
    L.append("")

    L += ["## 5. Presence of `complexity` / `missing_info`", "",
          "| split | in_scope rows lacking a key | non-in_scope rows having a key | status |", "|---|---|---|---|"]
    for s, rows in splits.items():
        ok = [r for r in rows if "_bad_line" not in r]
        lack = sum(1 for r in ok if r["labels"]["scope_check"] == "in_scope" and ("complexity" not in r["labels"] or "missing_info" not in r["labels"]))
        have = sum(1 for r in ok if r["labels"]["scope_check"] != "in_scope" and ("complexity" in r["labels"] or "missing_info" in r["labels"]))
        L.append(f"| {s} | {lack} | {have} | {'PASS' if not lack and not have else 'DIFF'} |")
        if lack or have:
            diffs.append(f"complexity/missing_info presence mismatch in {s}")
    L.append("")

    # 6 token lengths
    L += ["## 6. Serialized-state token length (reference tokenizer)", ""]
    if a.token_lengths and Path(a.token_lengths).exists():
        tl = json.load(open(a.token_lengths))
        L += ["| split | min | median | p95 | max | >512 | >768 | >1024 |", "|---|---|---|---|---|---|---|---|"]
        L.insert(len(L) - 2, f"Tokenizer: `{tl.get('_tokenizer')}`. State only (questions not included).")
        for s, v in tl.items():
            if s.startswith("_"):
                continue
            L.append(f"| {s} | {v['min']} | {v['median']} | {v['p95']} | {v['max']} | {v['gt512']} | {v['gt768']} | {v['gt1024']} |")
    else:
        L.append("_Pending: needs the reference tokenizer (P0 step 7). Re-run with `--token-lengths`._")
    L.append("")

    # 7 manifests
    L += ["## 7. Manifests", ""]
    for s in EXPECTED:
        mp = data / s / "manifest.json"
        m = json.load(open(mp))
        sha = hashlib.sha256(mp.read_bytes()).hexdigest()
        keys = ", ".join(m.keys())
        L.append(f"- **{s}**: sha256 `{sha}`; router count {m.get('counts', {}).get('router')}; "
                 f"release_status `{m.get('release_status')}`; verified_share {m.get('verified_share')}; seed {m.get('seed')}.")
        L.append(f"  - keys: {keys}")
        for k in ("split_policy", "split_by", "leakage", "bundles", "families"):
            if k in m:
                L.append(f"  - `{k}`: {json.dumps(m[k], ensure_ascii=False)[:300]}")
    fam = {s: set(r["support"].get("family") for r in rows if "_bad_line" not in r) for s, rows in splits.items()}
    bun = {s: set(r["support"].get("bundle_id") for r in rows if "_bad_line" not in r) for s, rows in splits.items()}
    L += ["", "Overlap of `support.family` and `support.bundle_id` across splits (leakage picture):", ""]
    for x, y in (("train", "validation"), ("train", "test"), ("validation", "test")):
        L.append(f"- {x}/{y}: families shared {len(fam[x] & fam[y])} (of {len(fam[x])}/{len(fam[y])}); bundles shared {len(bun[x] & bun[y])}")
    pairs = {s: set(r["support"].get("pair_id") for r in rows if "_bad_line" not in r and r["support"].get("pair_id")) for s, rows in splits.items()}
    for x, y in (("train", "validation"), ("train", "test"), ("validation", "test")):
        L.append(f"- pair_id shared {x}/{y}: {len(pairs[x] & pairs[y])}")
    L.append("")

    # 8 violations
    L += ["## 8. Schema violations", ""]
    total = 0
    for s, rows in splits.items():
        viol = [(r.get("query_id", "?"), v) for r in rows for v in [check_row(r)] if v]
        total += len(viol)
        L.append(f"- {s}: {len(viol)} rows with violations")
        for qid, v in viol[:15]:
            L.append(f"  - {qid}: {'; '.join(v)}")
        if viol:
            diffs.append(f"{len(viol)} schema violations in {s}")
    L.append("")

    # suspected label errors (information only)
    L += ["## Suspected label errors", "",
          "Only what the checks above surfaced; no row has been edited. "
          "All rows are `verified: false` (synthetic labels), so some noise is expected.", ""]
    nv = Counter(r["support"].get("verified") for rows in splits.values() for r in rows if "_bad_line" not in r)
    L.append(f"- `verified` values across all splits: {dict(nv)}")
    L.append("")

    L += ["## Summary", ""]
    if diffs:
        L.append(f"**{len(diffs)} DIFF(s). STOP and ask the owner before continuing.**")
        L += [f"- {d}" for d in diffs[:50]]
    else:
        L.append("No unresolved DIFF. One owner-accepted deviation from chapter 02: insurer omitted from required_slots on 140 rows (C-28).")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {a.out}; DIFFs: {len(diffs)}")
    for d in diffs[:50]:
        print("DIFF", d)


if __name__ == "__main__":
    main()
